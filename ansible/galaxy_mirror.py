#!/usr/bin/env python3
"""Helpers for jenkinsfile.galaxy-archive.

Run with the interpreter ansible-galaxy uses, so PyYAML and packaging are available.

  validate REQUIREMENTS            exact version pins only; reject ansible.builtin
  lock     REQUIREMENTS DIST OUT   write FQCN lockfile from downloaded tarballs,
                                   warn on transitive deps not pinned in REQUIREMENTS
  gate     DIST TARGET_CORE        fail if any collection's requires_ansible excludes TARGET_CORE
  list     DIST                    print "<fqcn> <version> <tarball filename>" per collection
"""
import glob
import json
import os
import re
import sys
import tarfile

import yaml
from packaging.specifiers import InvalidSpecifier, SpecifierSet
from packaging.version import Version

EXACT = re.compile(r'^(==)?\d+\.\d+\.\d+([-+][0-9A-Za-z.+-]+)?$')
BUILTIN = {'ansible.builtin', 'ansible.legacy'}


def die(msg):
    print(f'ERROR: {msg}', file=sys.stderr)
    sys.exit(1)


def load_requirements(path):
    with open(path) as f:
        data = yaml.safe_load(f) or {}
    cols = data.get('collections') if isinstance(data, dict) else None
    if not cols:
        die(f'{path}: no "collections" entries found')
    out = {}
    for c in cols:
        if not isinstance(c, dict) or 'name' not in c:
            die(f'{path}: every entry needs "name" and "version" keys, got {c!r}')
        out[c['name']] = str(c.get('version', '')).strip()
    return out


def read_tarball(path):
    with tarfile.open(path) as tf:
        info = json.load(tf.extractfile('MANIFEST.json'))['collection_info']
        try:
            runtime = yaml.safe_load(tf.extractfile('meta/runtime.yml')) or {}
        except KeyError:
            runtime = {}
    return {
        'fqcn': f"{info['namespace']}.{info['name']}",
        'version': info['version'],
        'requires_ansible': runtime.get('requires_ansible'),
        'tarball': path,
    }


def tarballs(dist):
    found = [read_tarball(p) for p in sorted(glob.glob(os.path.join(dist, '*.tar.gz')))]
    if not found:
        die(f'no collection tarballs in {dist}')
    return found


def cmd_validate(req):
    errors = []
    for name, ver in load_requirements(req).items():
        if name in BUILTIN:
            errors.append(f'{name}: ships inside ansible-core, it is not a Galaxy collection - remove it')
        elif not ver or not EXACT.match(ver):
            errors.append(f'{name}: version "{ver}" is not an exact pin (use e.g. version: "1.2.3")')
    if errors:
        die('invalid requirements:\n  ' + '\n  '.join(errors))
    print(f'{req}: OK')


def cmd_lock(req, dist, out):
    pinned = load_requirements(req)
    cols = tarballs(dist)
    for c in cols:
        if c['fqcn'] not in pinned:
            print(f"WARNING: transitive dependency {c['fqcn']} {c['version']} is not pinned "
                  f"in {req}; pin it to avoid drift between runs")
        elif pinned[c['fqcn']].lstrip('=') != c['version']:
            die(f"{c['fqcn']}: resolved {c['version']} but {req} pins {pinned[c['fqcn']]}")
    lock = {'collections': [{'name': c['fqcn'], 'version': c['version']} for c in cols]}
    with open(out, 'w') as f:
        f.write('# Generated by jenkinsfile.galaxy-archive - full resolved set incl. transitive deps\n')
        yaml.safe_dump(lock, f, sort_keys=False)
    print(f'Wrote {out}')


def cmd_gate(dist, target):
    core = Version(target)
    errors = []
    for c in tarballs(dist):
        spec = c['requires_ansible']
        if not spec:
            print(f"WARNING: {c['fqcn']} {c['version']} declares no requires_ansible")
            continue
        try:
            ok = SpecifierSet(spec).contains(core, prereleases=True)
        except InvalidSpecifier:
            die(f"{c['fqcn']}: unparsable requires_ansible {spec!r}")
        print(f"{'OK  ' if ok else 'FAIL'} {c['fqcn']} {c['version']} requires_ansible {spec}")
        if not ok:
            errors.append(c['fqcn'])
    if errors:
        die(f"not compatible with ansible-core {target}: {', '.join(errors)}")


def cmd_list(dist):
    for c in tarballs(dist):
        print(c['fqcn'], c['version'], os.path.basename(c['tarball']))


COMMANDS = {'validate': (cmd_validate, 1), 'lock': (cmd_lock, 3), 'gate': (cmd_gate, 2), 'list': (cmd_list, 1)}

if __name__ == '__main__':
    if len(sys.argv) < 2 or sys.argv[1] not in COMMANDS or len(sys.argv) - 2 != COMMANDS[sys.argv[1]][1]:
        die(__doc__)
    fn, _ = COMMANDS[sys.argv[1]]
    fn(*sys.argv[2:])